"""Writes skills/lowey/reference/coverage.md from LoweyCore's BridgeCoverage: every menu-bar command and what the Add
page makes, with its bridge path. `--check` (CI) fails when the file is out of date.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Packages/LoweyCore/Sources/LoweyCore/AI/BridgeCoverage.swift"
KEYS = ROOT / "Packages/LoweyFeatures/Sources/LoweyFeatures/Workspace/Support/KeyCommands.swift"
OUTPUT = ROOT / "skills/lowey/reference/coverage.md"
ENTRY = re.compile(r'"([A-Za-z0-9.]+)": \.(verb|app|tool)\(([^)]*)\)')
TITLE = re.compile(r'HmmKeyCommand\("([A-Za-z0-9.]+)", "([^"]*)", menu: "([^"]*)"')


def path(kind: str, args: str) -> str:
    parts = [a.strip() for a in args.split(",") if a.strip()]
    first = parts[0].strip('"').lstrip(".") if parts else ""
    rest = {k.strip(): v.strip().strip('"') for k, v in (p.split(":", 1) for p in parts[1:] if ":" in p)}
    if kind == "verb":
        return f'`{{"do": "{first}"' + (f', "op": "{rest["op"]}"' if "op" in rest else "") + "}`"
    if kind == "app":
        return f'`{{"do": "app", "op": "{first}"' + (f', "value": "{rest["value"]}"' if "value" in rest else "") + "}`"
    return f"the `{first}` tool"


def build() -> str:
    source = SOURCE.read_text(encoding="utf-8")
    titles = {m.group(1): (m.group(3), m.group(2)) for m in TITLE.finditer(KEYS.read_text(encoding="utf-8"))}
    making_at = source.index("public static let making")
    commands, making = [], []
    for match in ENTRY.finditer(source):
        (making if match.start() > making_at else commands).append((match.group(1), path(match.group(2), match.group(3))))
    lines = ["# What the bridge reaches", "",
             "*Generated by `Tools/gen-coverage.py` from LoweyCore's `BridgeCoverage`; CI checks it. Every menu-bar command has",
             "a path, and a test fails when one doesn't.*", "",
             "## The menu bar", "", "| Menu | Command | Bridge path |", "|---|---|---|"]
    for key, target in sorted(commands, key=lambda c: (titles.get(c[0], ("~", c[0]))[0], titles.get(c[0], ("", c[0]))[1])):
        menu, title = titles.get(key, ("?", key))
        lines.append(f"| {menu} | {title} | {target} |")
    lines += ["", "## What the Add page makes", "", "| Thing | Bridge path |", "|---|---|"]
    lines += [f"| {key} | {target} |" for key, target in making]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print("skills/lowey/reference/coverage.md is out of date: run python Tools/gen-coverage.py", file=sys.stderr)
            return 1
        print("The bridge's reach table is up to date.")
        return 0
    OUTPUT.write_bytes(text.encode("utf-8"))
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({text.count(chr(10))} lines).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
